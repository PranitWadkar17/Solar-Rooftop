// Flatted list of all models for backward-compatibility and global lookup
export const DEFAULT_PANEL_LIBRARY: PanelSpecification[] = MANUFACTURER_PROFILES.flatMap(
  (m) => m.models
);

export function getPanelById(id: string): PanelSpecification {
  return (
    DEFAULT_PANEL_LIBRARY.find((p) => p.id === id) ?? DEFAULT_PANEL_LIBRARY[0]
  );
}

export function getManufacturerByBrand(brand: string): ManufacturerProfile | undefined {
  return MANUFACTURER_PROFILES.find(
    (m) => m.brandName.toLowerCase() === brand.toLowerCase() || m.id === brand.toLowerCase()
  );
}
